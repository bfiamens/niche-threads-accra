export const DICTS: Record<Locale, Dict> = { en, de };
export type TKey = keyof Dict;

const Ctx = createContext<{ locale: Locale; setLocale: (l: Locale) => void; t: (k: TKey) => string }>({
  locale: "en", setLocale: () => {}, t: (k) => en[k],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("niche-locale");
    if (saved === "de" || saved === "en") setLocaleState(saved);
  }, []);
  useEffect(() => { document.documentElement.lang = locale; }, [locale]);
  const setLocale = (l: Locale) => { setLocaleState(l); window.localStorage.setItem("niche-locale", l); };
  return <Ctx.Provider value={{ locale, setLocale, t: (k) => DICTS[locale][k] ?? en[k] }}>{children}</Ctx.Provider>;
}
export const useI18n = () => useContext(Ctx);
